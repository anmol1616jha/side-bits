export function isDifficulty(value: unknown): value is Difficulty {
  return DIFFICULTIES.some((difficulty) => difficulty.value === value);
}

export function isKnownTopic(difficulty: Difficulty, topic: unknown): topic is string {
  return typeof topic === "string" && TOPICS[difficulty].includes(topic);
}

/**
 * A random topic at the given difficulty, avoiding `exclude` (recent picks)
 * while there are others left. `random` is injectable for tests.
 */
export function pickTopic(
  difficulty: Difficulty,
  exclude: readonly string[] = [],
  random: () => number = Math.random,
): string {
  const all = TOPICS[difficulty];
  const fresh = all.filter((topic) => !exclude.includes(topic));
  const pool = fresh.length > 0 ? fresh : all;
  return pool[Math.floor(random() * pool.length)]!;
}
